param(
    [Parameter(ValueFromRemainingArguments = $true)]
    [string[]]$Target = @("pmap.o")
)

$ErrorActionPreference = "Stop"

if ($Target.Count -eq 0) {
    $Target = @("pmap.o")
}

$scriptRoot = if ($PSScriptRoot) { $PSScriptRoot } else { Split-Path -Parent $MyInvocation.MyCommand.Path }
$repo = (Resolve-Path (Join-Path $scriptRoot "..")).Path
$workspace = Split-Path -Parent $repo
$obj = Join-Path $repo "BUILD\obj\RELEASE_RISCV32\osfmk\RELEASE"
$tmp = Join-Path $workspace "tmp"
New-Item -ItemType Directory -Force -Path $tmp | Out-Null
$env:TMP = $tmp
$env:TEMP = $tmp
$env:TMPDIR = $tmp

function Convert-ToForwardSlashPath([string]$Path) {
    return ($Path -replace "\\", "/")
}

function Update-GeneratedRepoPaths(
    [string]$ObjectDir,
    [string[]]$OldRepoPaths,
    [string]$NewRepoPath
) {
    $oldPaths = @($OldRepoPaths | Where-Object { $_ -and $_ -ne $NewRepoPath } | Select-Object -Unique)
    if ($oldPaths.Count -eq 0) {
        return
    }

    $generatedFiles = @(
        Get-ChildItem -LiteralPath $ObjectDir -File -ErrorAction SilentlyContinue |
            Where-Object {
                $_.Name -eq "Makedep" -or
                $_.Extension -in @(".d", ".rsp", ".filelist", ".lst")
            }
    )

    $updated = 0
    foreach ($file in $generatedFiles) {
        $content = Get-Content -LiteralPath $file.FullName -Raw
        if ($null -eq $content) {
            continue
        }

        $changed = $false
        foreach ($oldPath in $oldPaths) {
            if ($content.Contains($oldPath)) {
                $content = $content.Replace($oldPath, $NewRepoPath)
                $changed = $true
            }
        }
        if ($changed) {
            Set-Content -LiteralPath $file.FullName -Value $content -Encoding ASCII -NoNewline
            $updated++
        }
    }

    if ($updated -gt 0) {
        Write-Host ("Rebased {0} generated build files to {1}" -f $updated, $NewRepoPath)
    }
}

function Update-Riscv32Makedep([string]$ObjectDir) {
    if (-not (Test-Path -LiteralPath $ObjectDir)) {
        return
    }

    $depFiles = @(Get-ChildItem -LiteralPath $ObjectDir -Filter "*.d" -File -ErrorAction SilentlyContinue |
        Sort-Object Name)
    if ($depFiles.Count -eq 0) {
        return
    }

    $out = Join-Path $ObjectDir "Makedep"
    $tmpOut = "$out.tmp"
    $lines = New-Object System.Collections.Generic.List[string]
    $lines.Add("# Auto-generated by tools/riscv32-make-osfmk.ps1 from GCC -MD output.")
    $lines.Add("# Keeps direct RV32 object/filelist builds honest after header changes.")
    $lines.Add("")

    foreach ($dep in $depFiles) {
        foreach ($line in Get-Content -LiteralPath $dep.FullName) {
            $lines.Add($line)
        }
        $lines.Add("")
    }

    Set-Content -LiteralPath $tmpOut -Value $lines -Encoding ASCII
    Move-Item -LiteralPath $tmpOut -Destination $out -Force
}

foreach ($candidate in @(
    (Join-Path $workspace "msys64\ucrt64\bin"),
    (Join-Path $workspace "msys64\usr\bin")
)) {
    if (Test-Path -LiteralPath $candidate) {
        $env:PATH = "$candidate;$env:PATH"
    }
}

$repoPath = Convert-ToForwardSlashPath $repo
$makefilePath = Join-Path $obj "Makefile"
$oldRepoPath = $null
if (Test-Path -LiteralPath $makefilePath) {
    $sourceLine = Get-Content -LiteralPath $makefilePath -TotalCount 1
    if ($sourceLine -match '^SOURCE_DIR=(.+)$') {
        $oldRepoPath = $Matches[1].Trim()
    }
}

if (-not $oldRepoPath -or $oldRepoPath -ne $repoPath) {
    & (Join-Path $scriptRoot "riscv32-gen-config.ps1")
}
$candidateOldPaths = @($oldRepoPath)
if ($repoPath -match '^[A-Za-z]:/') {
    foreach ($driveLetter in [char[]](65..90)) {
        $candidateOldPaths += "${driveLetter}$($repoPath.Substring(1))"
    }
}
Update-GeneratedRepoPaths $obj $candidateOldPaths $repoPath

& (Join-Path $scriptRoot "riscv32-gen-mig-stubs.ps1")
Update-Riscv32Makedep $obj

$make = Join-Path $workspace "msys64\usr\bin\make.exe"
if (-not (Test-Path -LiteralPath $make)) {
    $make = "make"
}

$objPath = Convert-ToForwardSlashPath $obj

$vars = @(
    "SRCROOT=$repoPath",
    "OBJROOT=$(Convert-ToForwardSlashPath (Join-Path $repo 'BUILD\obj'))",
    "SYMROOT=$(Convert-ToForwardSlashPath (Join-Path $repo 'BUILD\sym'))",
    "DSTROOT=$(Convert-ToForwardSlashPath (Join-Path $repo 'BUILD\dst'))",
    "SOURCE=$repoPath/osfmk/",
    "RELATIVE_SOURCE_PATH=osfmk",
    "COMPONENT=osfmk",
    "TARGET=$objPath/",
    "RC_ARCHS=RISCV32",
    "ARCH_CONFIG=RISCV32",
    "KERNEL_CONFIG=RELEASE",
    "MACHINE_CONFIG=QEMU_VIRT",
    "MAKEJOBS=-j1",
    "PLATFORM=CaribeOS",
    "CC=riscv64-unknown-elf-gcc",
    "CXX=riscv64-unknown-elf-g++",
    "MIG=true",
    "MIGCC=riscv64-unknown-elf-gcc",
    "STRIP=riscv64-unknown-elf-strip",
    "NM=riscv64-unknown-elf-nm",
    "LIPO=true",
    "LIBTOOL=true",
    "UNIFDEF=true",
    "DSYMUTIL=true",
    "CTFCONVERT=true",
    "CTFSCRUB=true",
    "CTFMERGE=true",
    "CTFINSERT=true",
    "NMEDIT=true",
    "HOST_CC=gcc",
    "HOST_FLEX=flex",
    "HOST_BISON=bison",
    "HOST_CODESIGN=true",
    "INCL_MAKEDEP=TRUE"
)

& $make -C $obj @Target @vars
$exitCode = $LASTEXITCODE
if ($exitCode -eq 0) {
    Update-Riscv32Makedep $obj
}
exit $exitCode
